"""
StOpt Kernel Regression Benchmark Wrapper

StOpt (STochastic OPTimization library) provides efficient kernel regression
using grid-based methods with O(N log^(d-1) N) complexity.

StOpt Methods:
- LocalGridKernelRegression: Grid-based Gaussian kernel (used here)
- LaplacianConstKernelRegression: Laplacian kernel, constant (NW)
- LaplacianLinearKernelRegression: Laplacian kernel, local linear

Reference:
- https://gitlab.com/stochastic-control/StOpt
- Warin & Ginsbourger (2020), StOpt: Stochastic Optimization Library for C++

Generated by: benchmark_lpr_stopt.py
Run from repo root: python fastLPR_py/benchmarks/benchmark_lpr_stopt.py
"""
