# Import StOptReg (compiled C++ module)
try:
    import StOptReg
    HAS_STOPT = True
except ImportError:
    HAS_STOPT = False


def stopt_local_regression(x, y, bandwidth=0.1, factor=1.0, linear=True, xq=None):
    """
    Run StOpt LocalGridKernelRegression.

    Parameters
    ----------
    x : ndarray, shape (N, d)
        Input points
    y : ndarray, shape (N,) or (N, 1)
        Response values
    bandwidth : float or ndarray
        Kernel bandwidth (scalar or per-dimension)
    factor : float
        Grid density factor (1.0 = default resolution)
    linear : bool
        True for local linear regression, False for Nadaraya-Watson (constant)
    xq : ndarray, optional
        Query points for prediction. If None, predict at training points.

    Returns
    -------
    yhat : ndarray
        Fitted values (at training points or query points)
    time_sec : float
        Execution time in seconds

    Raises
    ------
    ImportError
        If StOptReg module is not available
    """
    if not HAS_STOPT:
        raise ImportError("StOptReg module not available. Compile StOpt with Python bindings.")

    # StOpt expects x as (d, N) - transpose if needed
    x = np.asarray(x, dtype=np.float64)
    if x.ndim == 1:
        x = x.reshape(1, -1)
    elif x.shape[0] > x.shape[1]:
        x = x.T

    # y as 1D array
    y = np.asarray(y, dtype=np.float64).ravel()

    # bandwidth as numpy array
    bandwidth = np.asarray(bandwidth, dtype=np.float64)
    if bandwidth.ndim == 0:  # scalar
        bandwidth = np.array([float(bandwidth)])

    # factor as numpy array
    factor = np.asarray(factor, dtype=np.float64)
    if factor.ndim == 0:
        factor = np.array([float(factor)])

    # Query points
    if xq is not None:
        xq = np.asarray(xq, dtype=np.float64)
        if xq.ndim == 1:
            xq = xq.reshape(1, -1)
        elif xq.shape[0] > xq.shape[1]:
            xq = xq.T
        predict_at_xq = True
    else:
        predict_at_xq = False

    t0 = time.time()

    # Create regressor: bZeroDate=False (normal regression)
    regressor = StOptReg.LocalGridKernelRegression(
        False,       # bZeroDate
        x,           # particles (d, N)
        bandwidth,   # bandwidth
        factor,      # factPoint
        linear       # bLin: True=local linear, False=NW
    )

    if predict_at_xq:
        # Get coefficients and predict at query points
        coef = regressor.getCoordBasisFunction(y)
        yhat = regressor.getValues(xq, coef)
    else:
        # Predict at training points
        yhat = regressor.getAllSimulations(y)

    elapsed = time.time() - t0

    return np.asarray(yhat), elapsed


def stopt_nw(x, y, bandwidth=0.1, factor=1.0, xq=None):
    """Convenience wrapper for Nadaraya-Watson (local constant) regression."""
    return stopt_local_regression(x, y, bandwidth, factor, linear=False, xq=xq)


def stopt_ll(x, y, bandwidth=0.1, factor=1.0, xq=None):
    """Convenience wrapper for local linear regression."""
    return stopt_local_regression(x, y, bandwidth, factor, linear=True, xq=xq)


def silverman_bandwidth(N, d):
    """
    Silverman's rule-of-thumb bandwidth for kernel regression.

    h = sigma * N^(-1/(4+d)) where sigma ~= 1 for standardized data.
    For unstandardized data, multiply by std(x).
    """
    return 1.0 * (N ** (-1.0 / (4 + d)))


def run_stopt_benchmark(x, y, d, N, linear=True, bandwidth=None):
    """
    Run StOpt benchmark with auto-selected bandwidth.

    Parameters
    ----------
    x : ndarray
        Input points
    y : ndarray
        Response values
    d : int
        Dimensionality
    N : int
        Number of samples
    linear : bool
        Use local linear (True) or NW (False)
    bandwidth : float, optional
        Override auto bandwidth selection

    Returns
    -------
    dict
        Benchmark results with keys: status, time_sec, error
    """
    if not HAS_STOPT:
        return {'status': 'skip', 'error': 'StOptReg not available'}

    # Auto-select bandwidth (Silverman-like rule)
    if bandwidth is None:
        bandwidth = silverman_bandwidth(N, d) * 0.5  # Slightly smaller for regression

    try:
        yhat, time_sec = stopt_local_regression(
            x, y, bandwidth=bandwidth, factor=1.0, linear=linear
        )
        return {
            'status': 'success',
            'time_sec': time_sec,
            'yhat': yhat,
            'bandwidth': bandwidth
        }
    except Exception as e:
        return {'status': 'error', 'error': str(e)}


