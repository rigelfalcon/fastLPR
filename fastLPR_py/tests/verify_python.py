# TEST 9: Heteroscedastic 1D (mean + variance estimation)
# Two-step process: 1) estimate mean, 2) estimate variance from residuals^2
# =============================================================================
def test_hetero_1d(mat):
    x = np.asarray(mat["x"]).reshape(-1, 1)
    y = np.asarray(mat["y"]).ravel()
    hlist = np.asarray(mat["hlist"]).reshape(-1, 1)

    # Step 1: Estimate mean
    opt_mean = {"order": 1, "verbose": False, "dstd": 0}
    if "dof_random_vectors_mean" in mat:
        opt_mean["random_matrix"] = np.asarray(mat["dof_random_vectors_mean"])
    res_mean = cv_fastlpr(x, y, hlist, opt_mean)

    # Step 2: Estimate variance from residuals^2
    residuals = y - res_mean.yhat
    opt_var = {"order": 1, "verbose": False, "y_type_out": "variance", "dstd": 1}
    if "dof_random_vectors_var" in mat:
        opt_var["random_matrix"] = np.asarray(mat["dof_random_vectors_var"])
    res_var = cv_fastlpr(x, residuals**2, hlist, opt_var)

    cv_result = res_mean.gcv_yhat or {}
    return {
        "n": len(x),
        "gcv_py": cv_result.get("scores"),
        "gcv_m": safe_extract(mat, "gcv_m"),
        "bw_py": res_mean.h,
        "bw_m": safe_extract(mat, "h1se_mean"),
        "mean_py": res_mean.yhat,
        "mean_m": safe_extract(mat, "yhat_mean"),
        "var_py": res_var.yhat,
        "var_m": safe_extract(mat, "yhat_var")
    }

results.append(run_test("Hetero 1D", "ref_hetero_1d.mat", 1, 1, "mean+var", test_hetero_1d))

