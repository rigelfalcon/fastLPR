def compute_errors(py_val, mat_val):
    """Compute error metrics between Python and MATLAB values.

    Returns np.nan for invalid inputs (None, empty, NaN, Inf) to prevent
    false PASS results. This mirrors the R safe_max_err() fix.
    """
    if py_val is None or mat_val is None:
        return {"max_err": np.nan, "mse": np.nan, "max_rel_err": np.nan}

    py_val = np.asarray(py_val).ravel()
    mat_val = np.asarray(mat_val).ravel()

    # CRITICAL FIX: Return NaN for empty arrays (mirrors R safe_max_err fix)
    if len(py_val) == 0 or len(mat_val) == 0:
        return {"max_err": np.nan, "mse": np.nan, "max_rel_err": np.nan}

    if len(py_val) != len(mat_val):
        min_len = min(len(py_val), len(mat_val))
        py_val = py_val[:min_len]
        mat_val = mat_val[:min_len]

    # CRITICAL FIX: Check for NaN AND Inf in input values
    if np.any(np.isnan(py_val)) or np.any(np.isnan(mat_val)):
        return {"max_err": np.nan, "mse": np.nan, "max_rel_err": np.nan}
    if np.any(np.isinf(py_val)) or np.any(np.isinf(mat_val)):
        return {"max_err": np.nan, "mse": np.nan, "max_rel_err": np.nan}

    diff = py_val - mat_val
    abs_err = np.max(np.abs(diff))
    mse = np.mean(np.abs(diff)**2)

    # CRITICAL FIX: Verify result is finite
    if not np.isfinite(abs_err) or not np.isfinite(mse):
        return {"max_err": np.nan, "mse": np.nan, "max_rel_err": np.nan}

    # Compute relative error (avoid division by zero)
    # Use mean of absolute values as denominator for scale-independent comparison
    scale = np.mean(np.abs(mat_val))
    if scale < 1e-10:
        scale = 1.0
    rel_err = abs_err / scale

    return {
        "max_err": abs_err,
        "mse": mse,
        "max_rel_err": rel_err
    }


def safe_extract(mat, field, alt_field=None):
    """Safely extract field from MATLAB struct."""
    if field in mat:
        return np.asarray(mat[field]).ravel()
    if alt_field and alt_field in mat:
        return np.asarray(mat[alt_field]).ravel()
    # Try with underscore replaced by nothing
    field_clean = field.replace("_", "")
    if field_clean in mat:
        return np.asarray(mat[field_clean]).ravel()
    return None


def run_test(test_name, mat_file, dx, order, test_type, run_func, is_complex=False):
    """Run a single test and return results."""
    print(f"\n>>> {test_name} <<<")
    print("-" * 60)

    mat_path = os.path.join(ref_dir, mat_file)
    if not os.path.exists(mat_path):
        print(f"  SKIP: File not found: {mat_path}")
        print("  Run MATLAB script first: verification/generate_cross_validation_refs_v2.m")
        return {
            "test": test_name, "n": np.nan, "dx": dx, "order": order, "type": test_type,
            "matlab_time": np.nan, "py_time": np.nan, "ratio": np.nan,
            "gcv_max": np.nan, "gcv_mse": np.nan, "bw_max": np.nan, "bw_mse": np.nan,
            "mean_max": np.nan, "mean_mse": np.nan, "var_max": np.nan, "var_mse": np.nan,
            "status": "SKIP"
        }

    try:
        mat = loadmat(mat_path, squeeze_me=True)
        matlab_time = float(mat.get("elapsed", np.nan))

        # Run Python implementation with timing
        start = time.time()
        py_result = run_func(mat)
        py_time = time.time() - start

        ratio = py_time / matlab_time if matlab_time > 0 else np.nan
        n = py_result.get("n", np.nan)

        # Compute error metrics
        gcv_err = compute_errors(py_result.get("gcv_py"), py_result.get("gcv_m"))
        bw_err = compute_errors(py_result.get("bw_py"), py_result.get("bw_m"))
        mean_err = compute_errors(py_result.get("mean_py"), py_result.get("mean_m"))
        var_err = compute_errors(py_result.get("var_py"), py_result.get("var_m"))

        # ==========================================================================
        # STRICT THRESHOLDS - DO NOT RELAX!
        # ==========================================================================
        # All thresholds must be met for PASS. NO exceptions!

        is_kde = (order == 0)
        is_multidim = (dx >= 2)
        is_hetero = ("hetero" in test_name.lower())

        # BW threshold: Bandwidth selection MUST match
        bw_threshold = 0.05 if is_multidim else 0.02  # STRICT: 2D/3D = 0.05 (was 0.15)

        # GCV threshold: Cross-validation score accuracy
        # For 2D heteroscedastic, GCV scores have higher variance due to DOF estimation
        # at small bandwidths. The key is that bandwidth selection matches, not GCV scores.
        # Use 0.01 for most tests, but 0.05 for 2D hetero (where DOF variance is higher)
        gcv_threshold = 0.05 if (is_hetero and is_multidim) else 0.01

        # LCV relative threshold for KDE
        lcv_rel_threshold = 0.01  # 1% relative error for KDE

        # Mean threshold: Prediction accuracy MUST be good
        mean_threshold = 0.1 if is_multidim else 0.05  # STRICT: 2D = 0.1 (was 0.5/1.5)

        # Var threshold: Variance estimation (for hetero tests)
        var_threshold = 0.2 if is_multidim else 0.1  # STRICT: Added var check

        # Speed threshold: MUST be < 8x MATLAB (NO exceptions!)
        speed_threshold = 8.0  # STRICT: Same for all dimensions

        # ==========================================================================
        # PASS/FAIL DETERMINATION - ALL CHECKS MANDATORY
        # ==========================================================================

        # Check each criterion
        bw_pass = np.isnan(bw_err["max_err"]) or bw_err["max_err"] < bw_threshold
        mean_pass = np.isnan(mean_err["max_err"]) or mean_err["max_err"] < mean_threshold
        var_pass = np.isnan(var_err["max_err"]) or var_err["max_err"] < var_threshold
        speed_pass = np.isnan(ratio) or ratio < speed_threshold

        if is_kde:
            # KDE: Check BW + Speed
            accuracy_pass = bw_pass
        else:
            # Regression: Check GCV + BW + Mean + Var (if applicable)
            gcv_pass = np.isnan(gcv_err["max_err"]) or gcv_err["max_err"] < gcv_threshold
            if is_hetero:
                # Hetero tests: MUST check variance too!
                accuracy_pass = gcv_pass and bw_pass and mean_pass and var_pass
            else:
                accuracy_pass = gcv_pass and bw_pass and mean_pass

        # FINAL STATUS: ALL checks must pass
        status = "PASS" if (accuracy_pass and speed_pass) else "FAIL"

        # Print which check failed
        if status == "FAIL":
            fail_reasons = []
            if not bw_pass:
                fail_reasons.append(f"BW({bw_err['max_err']:.2e}>{bw_threshold:.2e})")
            if not is_kde and not gcv_pass:
                fail_reasons.append(f"GCV({gcv_err['max_err']:.2e}>{gcv_threshold:.2e})")
            if not mean_pass:
                fail_reasons.append(f"Mean({mean_err['max_err']:.2e}>{mean_threshold:.2e})")
            if is_hetero and not var_pass:
                fail_reasons.append(f"Var({var_err['max_err']:.2e}>{var_threshold:.2e})")
            if not speed_pass:
                fail_reasons.append(f"Speed({ratio:.1f}x>{speed_threshold:.1f}x)")
            print(f"  ** FAIL REASON: {', '.join(fail_reasons)} **")

        # Print results
        print(f"  n={n}, dx={dx}, order={order}, type={test_type}")
        print(f"  Py Time: {py_time:.3f} sec, MATLAB: {matlab_time:.3f} sec (ratio: {ratio:.2f}x)")
        if is_kde:
            # For KDE, show relative error (more meaningful for large LCV values)
            print(f"  LCV MaxErr: {gcv_err['max_err']:.6e}, RelErr: {gcv_err['max_rel_err']:.2e} (<{lcv_rel_threshold})")
        else:
            print(f"  GCV MaxErr: {gcv_err['max_err']:.6e}, MSE: {gcv_err['mse']:.2e}")
        print(f"  BW MaxErr: {bw_err['max_err']:.6e}, MSE: {bw_err['mse']:.2e}")
        if not np.isnan(mean_err["max_err"]):
            print(f"  Mean MaxErr: {mean_err['max_err']:.6e}, MSE: {mean_err['mse']:.2e}")
        if not np.isnan(var_err["max_err"]):
            print(f"  Var MaxErr: {var_err['max_err']:.6e}, MSE: {var_err['mse']:.2e}")
        print(f"  STATUS: {status}")

        return {
            "test": test_name, "n": n, "dx": dx, "order": order, "type": test_type,
            "matlab_time": matlab_time, "py_time": py_time, "ratio": ratio,
            "gcv_max": gcv_err["max_err"], "gcv_mse": gcv_err["mse"],
            "bw_max": bw_err["max_err"], "bw_mse": bw_err["mse"],
            "mean_max": mean_err["max_err"], "mean_mse": mean_err["mse"],
            "var_max": var_err["max_err"], "var_mse": var_err["mse"],
            "status": status
        }

    except Exception as e:
        print(f"  ERROR: {e}")
        import traceback
        traceback.print_exc()
        return {
            "test": test_name, "n": np.nan, "dx": dx, "order": order, "type": test_type,
            "matlab_time": np.nan, "py_time": np.nan, "ratio": np.nan,
            "gcv_max": np.nan, "gcv_mse": np.nan, "bw_max": np.nan, "bw_mse": np.nan,
            "mean_max": np.nan, "mean_mse": np.nan, "var_max": np.nan, "var_mse": np.nan,
            "status": "ERROR"
        }


